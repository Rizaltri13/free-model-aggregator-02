// free-model-aggregator-02: one server, two client wires, and a real free model behind every answer.
//
// The -02 contest is LIVE where -01 was simulated: the six prompts of a trial are answered by real
// OpenRouter free models, dialled through the grader's gateway at $OPENAI_BASE_URL on the entrant's
// own pushed OpenRouter key (the sandbox only ever holds a dummy the gateway swaps). This entry:
//
//   1. listens on 0.0.0.0 at a free port (never 8080: the env itself is there on one layout);
//   2. POSTs $MAKEFUN_ENV_URL/register {"protocol_version": 1, "port": <port>, "catalog": <catalog>};
//   3. serves GET /v1/models (in the shape of the auth header it got: x-api-key means Anthropic,
//      Authorization means OpenAI), POST /v1/chat/completions and POST /v1/messages, each with a JSON
//      body or with server-sent events;
//   4. answers each prompt by dialling free models through the gateway, best first (see ROUTING);
//   5. polls GET $MAKEFUN_ENV_URL/work every 100 ms and exits 0 when the env says {"done": true}.
//
// `node main.ts --list` prints the catalog JSON and exits 0 before any server starts; the register
// body's catalog is that same document, byte for byte.
//
// ROUTING (where the score is won)
//   - quality (60%): the candidates that meet a prompt's requirements are ranked by the brief's
//     rating_milli, best first, the brief's order breaking ties, and the best is dialled first.
//   - failover (10%): a refused call is walked past — the next candidate is dialled, with one second
//     pass over the ranking, at most 8 calls for one prompt — and every refusal recovered from is
//     reported on the answer in the `x-makefun-upstream-failures` header, the only trail the
//     failover column can see for a served prompt.
//   - cooldowns: each model's run of consecutive refusals is remembered; a model whose run reaches 2
//     is demoted behind every healthy model for later prompts (never dropped), and a success clears
//     its run. A rate-limited free model tends to stay limited for the trial's few minutes.
//   - the catalog (5%): exactly the brief's free model ids, registered and listed on both auth
//     shapes — no more, no fewer.
//
// THE MODEL RULE
//   Whatever this server reports in a response's `model` field is the model it actually dialled,
//   spelled as the gateway spells it (`openrouter/<vendor>/<model>:free`): the provider's own answer
//   drops the prefix, so the dialled id is put back on every JSON answer and every streamed chunk.
//
// THE GATEWAY'S RULES
//   Only the Chat Completions route takes the trial's dummy key (the Messages route refuses these
//   ids), so Anthropic-shaped requests are translated to Chat Completions and back. A call naming no
//   output cap, or one over 8192, is refused before it is forwarded, so every dialled body names a
//   cap: the client's own, clamped, or a default of 1024.

